import { mkdir } from "node:fs/promises"
import { upstreamTree } from "../upstream"

const root = new URL("../..", import.meta.url).pathname
const tree = await upstreamTree()
const flags = await import(`${tree}/packages/schema/src/config/flag.ts`)

const registry: Array<[string, string]> = Object.entries(flags.registry)
const optInOnly: Array<string> = [...flags.optInOnly]
const localOnly: Array<string> = [...flags.localOnly]

const lines = [
  header(),
  `pub const WILDCARD: &str = ${literal(flags.wildcard)};`,
  "",
  "pub const REGISTRY: &[(&str, &str)] = &[",
  ...registry.map(([key, description]) => `    (${literal(key)}, ${literal(description)}),`),
  "];",
  "",
  optInOnly.length === 0
    ? "pub const OPT_IN_ONLY: &[&str] = &[];"
    : ["pub const OPT_IN_ONLY: &[&str] = &[", ...optInOnly.map((key) => `    ${literal(key)},`), "];"].join("\n"),
  localOnly.length === 0
    ? "pub const LOCAL_ONLY: &[&str] = &[];"
    : ["pub const LOCAL_ONLY: &[&str] = &[", ...localOnly.map((key) => `    ${literal(key)},`), "];"].join("\n"),
  "",
]

const directory = `${root}crates/config/src/generated`
const file = `${directory}/flags.rs`
await mkdir(directory, { recursive: true })
await Bun.write(file, lines.join("\n"))

const format = Bun.spawnSync(["rustfmt", "--edition", "2024", file], { stdout: "inherit", stderr: "inherit" })
if (format.exitCode !== 0) process.exit(format.exitCode ?? 1)

console.log(
  `flags: ${registry.length} registry entries, ${optInOnly.length} opt-in only, ${localOnly.length} local only`,
)

function header() {
  return "// Generated by script/gen/flags.ts from the upstream pin. Do not edit."
}

function literal(value: string) {
  return JSON.stringify(value)
}
