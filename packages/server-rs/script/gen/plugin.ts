import { mkdir } from "node:fs/promises"
import { upstreamCoreTree } from "../upstream"

const root = new URL("../..", import.meta.url).pathname
const tree = await upstreamCoreTree()
const effect = await import(Bun.resolveSync("effect", `${tree}/packages/core/src`))
const { PluginInternal } = await import(`${tree}/packages/core/src/plugin/internal.ts`)

const listed = await effect.Effect.runPromise(PluginInternal.list())
const guarded: Array<string> = [...PluginInternal.guarded]

const lines = [
  header(),
  "pub const PRE: &[&str] = &[",
  ...listed.pre.map((entry: { id: string }) => `    ${literal(entry.id)},`),
  "];",
  "",
  "pub const POST: &[&str] = &[",
  ...listed.post.map((entry: { id: string }) => `    ${literal(entry.id)},`),
  "];",
  "",
  "pub const GUARDED: &[&str] = &[",
  ...guarded.map((id) => `    ${literal(id)},`),
  "];",
  "",
]

const directory = `${root}crates/plugin/src/generated`
const file = `${directory}/builtins.rs`
await mkdir(directory, { recursive: true })
await Bun.write(file, lines.join("\n"))

const format = Bun.spawnSync(["rustfmt", "--edition", "2024", file], { stdout: "inherit", stderr: "inherit" })
if (format.exitCode !== 0) process.exit(format.exitCode ?? 1)

console.log(`plugin: ${listed.pre.length} pre, ${listed.post.length} post, ${guarded.length} guarded`)

function header() {
  return "// Generated by script/gen/plugin.ts from the pinned packages/core/src/plugin/internal.ts. Do not edit."
}

function literal(value: string) {
  return JSON.stringify(value)
}
