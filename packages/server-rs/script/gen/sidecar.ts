import path from "node:path"
import type { BunPlugin } from "bun"
import { upstreamCoreTree } from "../upstream"

const root = new URL("../..", import.meta.url).pathname

const protocol = Bun.spawnSync(["bun", "run", "cargo", "test", "-p", "opencode-sidecar", "--test", "all", "bindings"], {
  cwd: root,
  env: { ...process.env, OPENCODE_UPDATE_SIDECAR_PROTOCOL: "1" },
  stdout: "inherit",
  stderr: "inherit",
})
if (protocol.exitCode !== 0) process.exit(protocol.exitCode ?? 1)

const build = await Bun.build({
  entrypoints: [path.join(root, "host/src/main.ts")],
  target: "bun",
  format: "esm",
  minify: false,
})
if (!build.success) {
  for (const log of build.logs) console.error(log)
  process.exit(1)
}
if (build.outputs.length !== 1) {
  console.error(`sidecar: expected one bundle output, got ${build.outputs.length}`)
  process.exit(1)
}

const text = await build.outputs[0].text()
await Bun.write(
  path.join(root, "crates/sidecar/host/host.js"),
  `// Generated by script/gen/sidecar.ts from host/src. Do not edit.\n${text}`,
)

const tree = await upstreamCoreTree()
const from = path.join(tree, "packages/core/src")
const { discoverPluginRuntimeSpecifiers, pluginRuntimeLoaderCode } = await import(
  path.join(tree, "packages/plugin/src/runtime-modules.ts")
)
const entries = discoverPluginRuntimeSpecifiers(from)
const specifiers = [...entries.keys()].sort()

const prettier = await import("prettier")
const runtimeFile = path.join(root, "host/src/plugin/runtime-modules.gen.ts")
const runtimeModules = [
  "// Generated by script/gen/sidecar.ts from the pinned @opencode/plugin runtime. Do not edit.",
  "export const modules: Record<string, () => Record<string, unknown>> = {",
  ...specifiers.map((specifier) => `  ${JSON.stringify(specifier)}: ${pluginRuntimeLoaderCode(specifier, entries)},`),
  "}",
  "",
].join("\n")
await Bun.write(runtimeFile, await prettier.format(runtimeModules, { filepath: runtimeFile }))

const pinned: BunPlugin = {
  name: "pinned",
  setup(build) {
    build.onResolve({ filter: /^(@opencode\/(?:util|plugin|schema)|effect)(?:\/.*)?$/ }, (args) => ({
      path: Bun.resolveSync(args.path, from),
    }))
    build.onResolve({ filter: /^\.\/runtime\.js$/ }, (args) => {
      if (!args.importer.endsWith("packages/plugin/src/source.bun.ts")) return
      return { path: path.join(root, "host/src/plugin/runtime.ts") }
    })
    build.onResolve({ filter: /^node-gyp(?:\/.*)?$/ }, () => ({ path: "node-gyp", external: true }))
  },
}

const plugins = await Bun.build({
  entrypoints: [path.join(root, "host/src/plugin/index.ts")],
  target: "bun",
  format: "esm",
  minify: true,
  define: {
    __dirname: JSON.stringify("/__sidecar__"),
    __filename: JSON.stringify("/__sidecar__/index.js"),
  },
  plugins: [pinned],
})
if (!plugins.success) {
  for (const log of plugins.logs) console.error(log)
  process.exit(1)
}
if (plugins.outputs.length !== 1) {
  console.error(`sidecar: expected one plugin bundle output, got ${plugins.outputs.length}`)
  process.exit(1)
}

await Bun.write(
  path.join(root, "crates/sidecar/host/plugins.js"),
  `// Generated by script/gen/sidecar.ts from host/src/plugin and the pinned upstream modules. Do not edit.\n${await plugins.outputs[0].text()}`,
)
