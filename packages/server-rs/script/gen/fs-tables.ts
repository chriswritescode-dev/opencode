import { mkdir, realpath } from "node:fs/promises"
import { upstreamCoreTree } from "../upstream"

type MimeEntry = { source?: string; extensions?: string[] }

const FACET_SCORES: Record<string, number> = { "prs.": 100, "x-": 200, "x.": 300, "vnd.": 400, default: 900 }
const SOURCE_SCORES: Record<string, number> = { nginx: 10, apache: 20, iana: 40, default: 30 }
const TYPE_SCORES: Record<string, number> = { application: 1, font: 2, audio: 2, video: 3, default: 0 }

const root = new URL("../..", import.meta.url).pathname
const tree = await upstreamCoreTree()
const packageRoot = `${tree}/packages/core/node_modules/mime-types`
const manifest = (await Bun.file(`${packageRoot}/package.json`).json()) as { version?: string }
if (manifest.version !== "3.0.2") {
  console.error(`fs-tables: mime-types is ${manifest.version ?? "missing"}; expected 3.0.2`)
  process.exit(1)
}

const dbPath = Bun.resolveSync("mime-db/db.json", await realpath(packageRoot))
const db = (await Bun.file(dbPath).json()) as Record<string, MimeEntry>
const types = new Map<string, string>()

for (const [type, entry] of Object.entries(db)) {
  for (const extension of entry.extensions ?? []) {
    const current = types.get(extension)
    types.set(extension, preferred(current, type, db))
  }
}

const lines = [
  "// Generated by script/gen/fs-tables.ts from the upstream pin. Do not edit.",
  "pub static TYPES: &[(&str, &str)] = &[",
  ...[...types.keys()].sort().map((extension) => {
    const type = types.get(extension) ?? ""
    return `    (${literal(extension)}, ${literal(type)}),`
  }),
  "];",
  "",
]

const directory = `${root}crates/fs/src/generated`
const file = `${directory}/mime_types.rs`
await mkdir(directory, { recursive: true })
await Bun.write(file, lines.join("\n"))

const format = Bun.spawnSync(["rustfmt", "--edition", "2024", file], { stdout: "inherit", stderr: "inherit" })
if (format.exitCode !== 0) process.exit(format.exitCode ?? 1)

console.log(`fs-tables: ${types.size} extensions from ${Object.keys(db).length} MIME types`)

function preferred(current: string | undefined, type: string, db: Record<string, MimeEntry>) {
  const currentScore = current === undefined ? 0 : score(current, db[current]?.source)
  const typeScore = score(type, db[type]?.source)
  return current !== undefined && currentScore > typeScore ? current : type
}

function score(type: string, source = "default") {
  if (type === "application/octet-stream") return 0
  const [category, subtype = ""] = type.split("/")
  const facet = subtype.replace(/(\.|x-).*/, "$1")
  const facetScore = facet in FACET_SCORES ? FACET_SCORES[facet] : FACET_SCORES.default
  const sourceScore = source in SOURCE_SCORES ? SOURCE_SCORES[source] : SOURCE_SCORES.default
  const categoryScore = category in TYPE_SCORES ? TYPE_SCORES[category] : TYPE_SCORES.default
  return facetScore + sourceScore + categoryScore + (1 - type.length / 100)
}

function literal(value: string) {
  return JSON.stringify(value)
}
