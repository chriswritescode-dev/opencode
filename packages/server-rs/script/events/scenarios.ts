const insertMessage = (
  session: string,
  id: string,
  type: string,
  seq: number,
  created: number,
  data: unknown,
  updated = created,
) =>
  `INSERT INTO session_message (id, session_id, type, seq, time_created, time_updated, data) VALUES ('${id}', '${session}', '${type}', ${seq}, ${created}, ${updated}, '${JSON.stringify(data)}')`

